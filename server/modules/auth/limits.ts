// Единые ограничения на регистрацию проверок звонком.
// Лимиты «на номер» и «на IP» не спасают от атакующего, который меняет номера и IP,
// поэтому последняя линия защиты — глобальный дневной бюджет проверок:
// это жёсткий потолок числа регистраций, независимо от того, как меняются источники.
export const HOUR_MS = 60 * 60_000
export const DAY_MS = 24 * HOUR_MS

/** Пауза между повторными регистрациями проверки на один номер. */
export const SEND_COOLDOWN_MS = 60_000

/** Сколько проверок в час может запросить один номер. */
export const PHONE_HOURLY_LIMIT = 5

/** Сколько проверок в сутки может запросить один номер. */
export const PHONE_DAILY_LIMIT = 5

/** Сколько проверок в час может запросить один IP (все номера вместе). */
export const IP_HOURLY_LIMIT = 20

/**
 * Жёсткий потолок регистраций на весь сервис в сутки — страховка от «вымогательства»
 * бюджета звонков: даже если атакующий меняет номера и IP,
 * расход не превысит этот бюджет. При превышении новые проверки не создаются никому.
 */
export const GLOBAL_DAILY_LIMIT = 200
