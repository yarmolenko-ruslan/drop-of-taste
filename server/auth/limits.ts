// Единые ограничения на отправку кодов подтверждения.
// Лимиты «на номер» и «на IP» не спасают от атакующего, который меняет номера и IP,
// поэтому последняя линия защиты — глобальный дневной бюджет SMS (globalDailyLimit):
// это жёсткий потолок расходов на отправку, независимо от того, как меняются источники.
export const HOUR_MS = 60 * 60_000
export const DAY_MS = 24 * HOUR_MS

/** Пауза между повторными запросами кода на один номер. */
export const SEND_COOLDOWN_MS = 60_000

/** Сколько кодов в час может запросить один номер. */
export const PHONE_HOURLY_LIMIT = 5

/** Сколько кодов в сутки может запросить один номер. */
export const PHONE_DAILY_LIMIT = 10

/** Сколько кодов в час может запросить один IP (все номера вместе). */
export const IP_HOURLY_LIMIT = 20

/**
 * Жёсткий потолок отправок на весь сервис в сутки — страховка от «вымогательства»
 * SMS-бюджета (message pumping): даже если атакующий меняет номера и IP,
 * расход не превысит этот бюджет. При превышении коды не отправляются никому.
 */
export const GLOBAL_DAILY_LIMIT = 200
